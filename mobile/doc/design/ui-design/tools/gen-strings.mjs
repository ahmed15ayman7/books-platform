// Generates bp/strings.js from the app's translation JSON so prototype copy always equals shipped copy.
// Run:  node tools/gen-strings.mjs   (from mobile/doc/design/ui-design)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.resolve(here, '../../../../assets/translations');

function flatten(obj, prefix = '', out = {}) {
  for (const [k, v] of Object.entries(obj)) {
    const key = prefix ? `${prefix}.${k}` : k;
    if (v && typeof v === 'object') flatten(v, key, out);
    else out[key] = v;
  }
  return out;
}

const str = {};
for (const lang of ['ar', 'en']) {
  str[lang] = flatten(JSON.parse(readFileSync(path.join(dir, `${lang}.json`), 'utf8')));
}

const banner = '// GENERATED by tools/gen-strings.mjs from mobile/assets/translations/{ar,en}.json — do not edit.\n';
writeFileSync(
  path.resolve(here, '../bp/strings.js'),
  `${banner}window.BP = window.BP || {};\nwindow.BP.STR = ${JSON.stringify(str, null, 1)};\n`,
);
console.log('bp/strings.js written:', Object.keys(str.ar).length, 'ar keys,', Object.keys(str.en).length, 'en keys');
