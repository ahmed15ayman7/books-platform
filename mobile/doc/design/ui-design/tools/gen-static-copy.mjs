// Generates bp/copy-static.js from the const copy blocks in the Flutter static-page and onboarding sources,
// so hard-coded (non-JSON) copy stays identical to the app.  Run: node tools/gen-static-copy.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const feat = path.resolve(here, '../../../../lib/features');
const SOURCES = {
  about: 'static_pages/presentation/screens/about_screen/about_body.dart',
  services: 'static_pages/presentation/screens/services_screen/services_body.dart',
  team: 'static_pages/presentation/screens/team_screen/team_body.dart',
  legal: 'static_pages/presentation/screens/static_page_screen/legal_page_body.dart',
  onboarding: 'onboarding/presentation/pages/onboarding_screen/onboarding_slide_page.dart',
};

/* Splits Dart source into string and non-string chunks so structural rewrites never touch text inside quotes. */
function chunks(src) {
  const out = [];
  let i = 0;
  let buf = '';
  while (i < src.length) {
    const c = src[i];
    if (c === "'" || c === '"') {
      if (buf) out.push({ code: buf });
      buf = '';
      let j = i + 1;
      while (j < src.length && src[j] !== c) j += src[j] === '\\' ? 2 : 1;
      out.push({ str: src.slice(i, j + 1) });
      i = j + 1;
    } else if (c === '/' && src[i + 1] === '/') {
      while (i < src.length && src[i] !== '\n') i++;
    } else {
      buf += c;
      i++;
    }
  }
  if (buf) out.push({ code: buf });
  return out;
}

function toJs(code) {
  return code
    .replace(/\bconst\s+/g, '')
    .replace(/<\s*\w+(\s*,\s*\w+)*\s*>(?=\s*[[{(])/g, '')
    .replace(/Color\(0xFF([0-9A-Fa-f]{6})\)/g, "'#$1'")
    .replace(/TeamMemberUrls\.\w+/g, 'null') // remote photos: the prototype shows the initials fallback
    .replace(/Icons\.(\w+)/g, "'$1'")
    .replace(/AppColors\.(\w+)/g, "'$1'")
    .replace(/\bOnboardingSlide\(/g, '{')
    .replace(/\(/g, '{')
    .replace(/\)/g, '}');
}

function extract(file, startMarker) {
  const text = readFileSync(path.join(feat, file), 'utf8');
  const start = text.indexOf(startMarker);
  const endClass = text.search(/\n(class|final class|abstract class) /);
  const region = text.slice(start, endClass > start ? endClass : undefined);
  const js = chunks(region)
    .map((c) => (c.str != null ? c.str : toJs(c.code)))
    .join('');
  // "const _name = expr;" -> statements
  const stmts = [];
  let depth = 0;
  let cur = '';
  for (const ch of chunks(js)) {
    if (ch.str != null) {
      cur += ch.str;
      continue;
    }
    for (const c of ch.code) {
      if (c === '{' || c === '[') depth++;
      if (c === '}' || c === ']') depth--;
      if (c === ';' && depth === 0) {
        stmts.push(cur.trim());
        cur = '';
      } else cur += c;
    }
  }
  const obj = {};
  for (const s of stmts) {
    const m = s.match(/^(?:final\s+)?(\w+)\s*=\s*([\s\S]+)$/);
    if (!m) continue;
    obj[m[1].replace(/^_/, '')] = new Function(`return (${m[2]});`)();
  }
  return obj;
}

const staticDir = path.resolve(here, '../../../../assets/static');
const md = (n) => readFileSync(path.join(staticDir, n), 'utf8');

const out = {
  md: { privacy: { ar: md('privacy_ar.md'), en: md('privacy_en.md') }, terms: { ar: md('terms_ar.md'), en: md('terms_en.md') } },
  about: extract(SOURCES.about, 'const _pageTitle'),
  services: extract(SOURCES.services, 'const _pageTitle'),
  team: extract(SOURCES.team, 'const _pageTitle'),
  legal: extract(SOURCES.legal, 'const _termsTitle'),
  onboardingSlides: extract(SOURCES.onboarding, 'const kOnboardingSlides').kOnboardingSlides,
};

const banner = '// GENERATED by tools/gen-static-copy.mjs from the Flutter static_pages / onboarding sources — do not edit.\n';
writeFileSync(path.resolve(here, '../bp/copy-static.js'), `${banner}window.BP = window.BP || {};\nwindow.BP.COPY = ${JSON.stringify(out, null, 1)};\n`);
console.log('copy-static.js:', Object.entries(out).map(([k, v]) => `${k}(${Object.keys(v).length})`).join(' '));
